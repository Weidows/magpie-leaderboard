import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';

export async function fetchText(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 60_000);
  try {
    const response = await fetch(url, {
      headers: {
        'user-agent': UA,
        accept: 'text/html,application/xhtml+xml,application/json;q=0.9,*/*;q=0.8',
        'accept-language': 'zh-CN,zh;q=0.9,en;q=0.8',
      },
      redirect: 'follow',
      signal: controller.signal,
    });
    if (!response.ok) {
      throw new Error(`${url} -> HTTP ${response.status}`);
    }
    return await response.text();
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Next.js App Router streams server components as `self.__next_f.push([1,"..."])`.
 * Join the decoded chunks into one big flight payload, then pluck the JSON we need.
 */
export function decodeNextFlight(html) {
  const chunks = [];
  const pattern = /self\.__next_f\.push\((\[[\s\S]*?\])\)<\/script>/g;
  let match;
  while ((match = pattern.exec(html))) {
    try {
      const payload = JSON.parse(match[1]);
      if (typeof payload[1] === 'string') chunks.push(payload[1]);
      else if (payload[1] != null) chunks.push(JSON.stringify(payload[1]));
    } catch {
      // A malformed chunk is not fatal; the data we need lives in one of the others.
    }
  }
  return chunks.join('');
}

/** Extract a JSON array/object that starts right after `"key":` without trusting its end marker. */
export function extractJsonAfter(source, key) {
  const marker = `"${key}":`;
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`missing ${marker} in flight payload`);
  const from = start + marker.length;
  const first = source[from];
  if (first !== '[' && first !== '{') {
    throw new Error(`${marker} does not start with JSON at ${from}`);
  }
  const close = first === '[' ? ']' : '}';
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = from; i < source.length; i += 1) {
    const char = source[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') {
      inString = true;
      continue;
    }
    if (char === first) depth += 1;
    else if (char === close) {
      depth -= 1;
      if (depth === 0) return source.slice(from, i + 1);
    }
  }
  throw new Error(`unterminated JSON after ${marker}`);
}

export function round(value, digits = 1) {
  if (value == null || !Number.isFinite(Number(value))) return null;
  const factor = 10 ** digits;
  return Math.round(Number(value) * factor) / factor;
}

export function pct(value, digits = 1) {
  if (value == null || !Number.isFinite(Number(value))) return null;
  return round(Number(value) * 100, digits);
}

export function today() {
  const now = new Date();
  const local = new Date(now.getTime() - now.getTimezoneOffset() * 60_000);
  return local.toISOString().slice(0, 10);
}

export async function writeModule(relativePath, variable, data) {
  const target = resolve(ROOT, relativePath);
  await mkdir(dirname(target), { recursive: true });
  const header = `/* Generated by scripts/${variable.includes('HARNESS') ? 'sync-harness' : 'sync-aa'}.mjs on ${new Date().toISOString()}. Do not edit by hand. */\n`;
  const body = `window.${variable} = ${JSON.stringify(data, null, 2)};\n`;
  await writeFile(target, header + body, 'utf8');
  return target;
}
